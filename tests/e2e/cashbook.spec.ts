import { expect, test } from '@playwright/test'
import { mockSupabase, signIn } from './supabase-mock'

test('muhasebeci kasa ekler, yeniler, düzenler ve denetim uyarısıyla siler', async ({ context, page }) => {
  await mockSupabase(context, { cashbookRole: 'accountant' })
  await signIn(page)
  await page.goto('/cashbook')
  const summary = page.getByRole('region', { name: 'Seçilen ayın kasa özeti' })
  const form = page.getByRole('form', { name: 'Kasa kayıt formu' })
  await expect(page.getByRole('button', { name: 'Kayıt ekle' })).toBeEnabled()
  await page.getByRole('button', { name: 'Kayıt ekle' }).click()
  await form.getByLabel('Açıklama').fill('Kasaya nakit giriş')
  await form.getByLabel('İşlem Türü').fill('Nakit')
  await form.getByLabel('Tarih', { exact: true }).fill('24.11.2026')
  await form.getByLabel('Borç (Giren)').fill('0,10')
  await form.getByRole('button', { name: 'Kaydet', exact: true }).click()
  await expect(form).toBeHidden()
  await expect(summary.getByText('0,10 TL')).toHaveCount(2)
  await page.reload()
  await expect(page.getByRole('cell', { name: 'Kasaya nakit giriş', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Kaydı düzenle: Kasaya nakit giriş' }).click()
  await form.getByLabel('Borç (Giren)').fill('0')
  await form.getByLabel('Alacak (Çıkan)').fill('0,20')
  await form.getByRole('button', { name: 'Kaydet', exact: true }).click()
  await expect(form).toBeHidden()
  await expect(summary.getByText('-0,20 TL')).toBeVisible()
  await page.getByRole('button', { name: 'Aralık 2026', exact: true }).click()
  await expect(summary.getByText('0,00 TL')).toHaveCount(3)
  await page.getByRole('button', { name: 'Kasım 2026', exact: true }).click()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Kaydı sil: Kasaya nakit giriş' }).click()
  await expect(page.getByRole('heading', { name: 'Henüz kasa kaydı yok' })).toBeVisible()
  await page.reload()
  await expect(summary.getByText('0,00 TL')).toHaveCount(3)
})
